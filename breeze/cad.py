"""Parametric CAD for the Zenith Plate building.

Every dimension derives from a handful of driving parameters (DesignParams). The
same rules are mirrored in cad/zenith_plate.scad (OpenSCAD) and in the
interactive viewer, so the three representations stay in lock-step.

Coordinate system: x = East, y = North, z = Up, metres.
"""
from __future__ import annotations

import json
from dataclasses import dataclass, asdict, field

import numpy as np


@dataclass
class DesignParams:
    # site / programme
    plot_x: float = 72.0            # E-W length of plate (m)
    plot_y: float = 48.0            # N-S depth of plate (m)
    plate_height: float = 6.0       # top of plate at its edges, above grade (m)
    camber: float = 0.04            # rise / short span of the doubly-curved plate (CAE-7)
    enclosure_inset: float = 6.0    # enclosed programme set back under plate (m)
    enclosure_height: float = 4.2   # single-storey programme (m)
    # skin cell (square inverted-pyramid, specular walls). CAE-3/6 drive the
    # acceptance angle to ~85 deg: the cavity collapses into a film-support rib grid.
    cell_pitch: float = 0.30        # aperture side (m)
    accept_deg: float = 85.0        # acceptance half-angle theta_a (deg)
    truncation: float = 1.0         # fraction of ideal wall height kept
    base_sheet: float = 1.5e-3      # roll-bond Al emitter/channel sheet (m)
    wall_sheet: float = 0.3e-3      # rib sheet (m)
    core: float = 0.08              # PIR core of sandwich tile (CAE-5)
    channel_pitch: float = 0.15     # hydronic channel pitch (CAE-4)
    # structure
    tile: float = 3.0               # prefabricated tile side (m)
    column_grid: float = 12.0       # tree-column spacing (m); branch tips form a grid/2 grillage
    fork_drop: float = 2.2          # trunk fork below grillage (m)
    beam_depth: float = 0.28        # glulam grillage depth (CAE-5)
    # storage
    tank_volume_m3: float = 250.0

    # ---------- derived
    @property
    def emitter_half(self):
        return 0.5 * self.cell_pitch * np.sin(np.radians(self.accept_deg))

    @property
    def cell_height(self):
        t = 0.5 * self.cell_pitch
        return self.truncation * (t + self.emitter_half) / np.tan(np.radians(self.accept_deg))

    @property
    def emitter_fraction(self):
        return (2 * self.emitter_half / self.cell_pitch) ** 2

    def derived(self):
        return {
            "emitter_half_width_m": self.emitter_half,
            "cell_height_m": self.cell_height,
            "emitter_area_fraction": self.emitter_fraction,
            "cells_total": int(round(self.plot_x / self.cell_pitch) * round(self.plot_y / self.cell_pitch)),
            "plate_area_m2": self.plot_x * self.plot_y,
            "enclosed_floor_m2": (self.plot_x - 2 * self.enclosure_inset) * (self.plot_y - 2 * self.enclosure_inset),
            "columns": (int(self.plot_x // self.column_grid)) * (int(self.plot_y // self.column_grid)),
            "camber_rise_m": self.camber * min(self.plot_x, self.plot_y),
            "tiles": int(round(self.plot_x / self.tile) * round(self.plot_y / self.tile)),
            "wall_area_per_m2_roof": self.wall_area_ratio(),
        }

    def wall_area_ratio(self):
        t, e, h = 0.5 * self.cell_pitch, self.emitter_half, self.cell_height
        slant = np.hypot(h, t - e)
        return 4 * (t + e) * slant / self.cell_pitch**2


# ------------------------------------------------------------------ mesh kit
class Mesh:
    def __init__(self):
        self.groups = {}

    def add(self, group, V, F):
        g = self.groups.setdefault(group, [np.zeros((0, 3)), np.zeros((0, 3), int)])
        F = np.asarray(F, int) + len(g[0])
        g[0] = np.vstack([g[0], np.asarray(V, float)])
        g[1] = np.vstack([g[1], F])

    def write_obj(self, path, mtl_name=None):
        off = 0
        with open(path, "w") as f:
            f.write("# Zenith Plate - generated by breeze.cad\n")
            if mtl_name:
                f.write(f"mtllib {mtl_name}\n")
            for name, (V, F) in self.groups.items():
                f.write(f"o {name}\n")
                if mtl_name:
                    f.write(f"usemtl {name.split('_')[0]}\n")
                for v in V:
                    f.write(f"v {v[0]:.5f} {v[1]:.5f} {v[2]:.5f}\n")
                for t in F + 1 + off:
                    f.write(f"f {t[0]} {t[1]} {t[2]}\n")
                off += len(V)

    def write_stl(self, path):
        tris = np.concatenate([V[F] for V, F in self.groups.values()])
        n = np.cross(tris[:, 1] - tris[:, 0], tris[:, 2] - tris[:, 0])
        n /= np.linalg.norm(n, axis=1, keepdims=True) + 1e-30
        rec = np.zeros(len(tris), dtype=[("n", "<f4", 3), ("v", "<f4", (3, 3)), ("a", "<u2")])
        rec["n"], rec["v"] = n, tris
        with open(path, "wb") as f:
            f.write(b"Zenith Plate".ljust(80, b" "))
            f.write(np.uint32(len(tris)).tobytes())
            f.write(rec.tobytes())


def box_mesh(c0, c1):
    x0, y0, z0 = c0
    x1, y1, z1 = c1
    V = [[x0, y0, z0], [x1, y0, z0], [x1, y1, z0], [x0, y1, z0], [x0, y0, z1], [x1, y0, z1], [x1, y1, z1], [x0, y1, z1]]
    F = [[0, 2, 1], [0, 3, 2], [4, 5, 6], [4, 6, 7], [0, 1, 5], [0, 5, 4], [1, 2, 6], [1, 6, 5], [2, 3, 7], [2, 7, 6], [3, 0, 4], [3, 4, 7]]
    return V, F


def cylinder_mesh(c, r, h, n=32):
    a = np.linspace(0, 2 * np.pi, n, endpoint=False)
    V = [[c[0] + r * np.cos(t), c[1] + r * np.sin(t), c[2] + z] for z in (0, h) for t in a]
    V += [[c[0], c[1], c[2]], [c[0], c[1], c[2] + h]]
    F = []
    for i in range(n):
        j = (i + 1) % n
        F += [[i, j, n + j], [i, n + j, n + i], [2 * n, j, i], [2 * n + 1, n + i, n + j]]
    return V, F


def strut_mesh(p0, p1, r, n=10):
    p0, p1 = np.asarray(p0, float), np.asarray(p1, float)
    ax = p1 - p0
    L = np.linalg.norm(ax)
    ax /= L
    a = np.array([1.0, 0, 0]) if abs(ax[0]) < 0.9 else np.array([0, 1.0, 0])
    u = np.cross(ax, a); u /= np.linalg.norm(u)
    w = np.cross(ax, u)
    t = np.linspace(0, 2 * np.pi, n, endpoint=False)
    ring = np.cos(t)[:, None] * u + np.sin(t)[:, None] * w
    V = np.vstack([p0 + r * ring, p1 + r * ring])
    F = []
    for i in range(n):
        j = (i + 1) % n
        F += [[i, j, n + j], [i, n + j, n + i]]
    return V, F


def funnel_cell_mesh(p: DesignParams, closed=True):
    """One skin cell in local coords: aperture centred at (0,0,h), emitter at z=0.
    Returns {'emitter': (V,F), 'mirror': (V,F)}."""
    t, e, h = 0.5 * p.cell_pitch, p.emitter_half, p.cell_height
    B = [[-e, -e, 0], [e, -e, 0], [e, e, 0], [-e, e, 0]]
    T = [[-t, -t, h], [t, -t, h], [t, t, h], [-t, t, h]]
    Vm = B + T
    Fm = []
    for i in range(4):
        j = (i + 1) % 4
        Fm += [[i, j, 4 + j], [i, 4 + j, 4 + i]]
    out = {"mirror": (Vm, Fm), "emitter": (B, [[0, 1, 2], [0, 2, 3]])}
    if closed:  # base sheet under the walls (structural flange)
        out["base"] = box_mesh([-t, -t, -p.base_sheet], [t, t, 0])
    return out


def plate_z(p: DesignParams, x, y):
    """Top-of-plate elevation: doubly-curved (product-parabola) camber, edges at plate_height."""
    rise = p.camber * min(p.plot_x, p.plot_y)
    return p.plate_height + rise * (1 - (2 * x / p.plot_x) ** 2) * (1 - (2 * y / p.plot_y) ** 2)


def grid_surface(p, depth, nx=48, ny=32):
    """Closed slab following the camber (top = emitter plane, bottom = low-e soffit)."""
    X, Y = p.plot_x, p.plot_y
    xs, ys = np.linspace(-X / 2, X / 2, nx + 1), np.linspace(-Y / 2, Y / 2, ny + 1)
    GX, GY = np.meshgrid(xs, ys, indexing="ij")
    top = np.stack([GX, GY, plate_z(p, GX, GY)], -1).reshape(-1, 3)
    bot = top - [0, 0, depth]
    V = np.vstack([top, bot])
    off = len(top)
    F = []
    vid = lambda i, j: i * (ny + 1) + j
    for i in range(nx):
        for j in range(ny):
            a, b, c, d = vid(i, j), vid(i + 1, j), vid(i + 1, j + 1), vid(i, j + 1)
            F += [[a, b, c], [a, c, d], [off + a, off + c, off + b], [off + a, off + d, off + c]]
    edges = [(vid(i, 0), vid(i + 1, 0)) for i in range(nx)] + [(vid(nx, j), vid(nx, j + 1)) for j in range(ny)] + \
            [(vid(i + 1, ny), vid(i, ny)) for i in range(nx)] + [(vid(0, j + 1), vid(0, j)) for j in range(ny)]
    for a, b in edges:
        F += [[a, off + a, off + b], [a, off + b, b]]
    return V, F


def building(p: DesignParams, cell_patch=6.0):
    """Assemble the building. The full cell array (~38k cells) is represented by the
    cambered plate; a `cell_patch` x `cell_patch` m detail patch at the SE corner
    carries explicit cell geometry (the viewer instances it across the plate)."""
    m = Mesh()
    X, Y, g = p.plot_x, p.plot_y, p.column_grid
    depth = p.core + p.base_sheet + 0.0007
    m.add("plate_slab", *grid_surface(p, depth))
    # grillage on the uniform g/2 grid formed by branch tips (offset g/4 from column lines)
    h = g / 2
    lines_x = np.arange(-X / 2 + g / 4, X / 2, h)
    lines_y = np.arange(-Y / 2 + g / 4, Y / 2, h)
    for x in lines_x:
        ys = np.linspace(-Y / 2, Y / 2, 33)
        for y0, y1 in zip(ys[:-1], ys[1:]):
            z0, z1 = plate_z(p, x, y0) - depth, plate_z(p, x, y1) - depth
            V, F = box_mesh([x - 0.1, y0, -p.beam_depth], [x + 0.1, y1, 0])
            V = np.array(V); V[:, 2] += np.where(V[:, 1] < (y0 + y1) / 2, z0, z1)
            m.add("structure_grillage", V, F)
    for y in lines_y:
        xs = np.linspace(-X / 2, X / 2, 49)
        for x0, x1 in zip(xs[:-1], xs[1:]):
            z0, z1 = plate_z(p, x0, y) - depth, plate_z(p, x1, y) - depth
            V, F = box_mesh([x0, y - 0.1, -p.beam_depth], [x1, y + 0.1, 0])
            V = np.array(V); V[:, 2] += np.where(V[:, 0] < (x0 + x1) / 2, z0, z1)
            m.add("structure_grillage", V, F)
    # tree columns at g centres, 4 diagonal branches to grillage nodes at (+-g/4, +-g/4)
    for x in np.arange(-X / 2 + g / 2, X / 2, g):
        for y in np.arange(-Y / 2 + g / 2, Y / 2, g):
            zb = min(plate_z(p, x + dx * g / 4, y + dy * g / 4) for dx in (-1, 1) for dy in (-1, 1)) - depth - p.beam_depth
            fork = zb - p.fork_drop
            m.add("structure_trunks", *cylinder_mesh([x, y, 0], 0.137, fork, 20))
            for dx, dy in ((1, 1), (1, -1), (-1, 1), (-1, -1)):
                tx, ty = x + dx * g / 4, y + dy * g / 4
                m.add("structure_branches", *strut_mesh([x, y, fork], [tx, ty, plate_z(p, tx, ty) - depth - p.beam_depth], 0.084))
    # enclosure (low-e clad box)
    i = p.enclosure_inset
    m.add("enclosure_lowe", *box_mesh([-X / 2 + i, -Y / 2 + i, 0], [X / 2 - i, Y / 2 - i, p.enclosure_height]))
    # thermal storage tank (buried)
    r_t = (p.tank_volume_m3 / (np.pi * 5.0)) ** 0.5
    m.add("tank_water", *cylinder_mesh([0, 0, -6.0], r_t, 5.0, 48))
    # explicit cell patch at SE corner
    cell = funnel_cell_mesh(p, closed=False)
    n = int(cell_patch / p.cell_pitch)
    for a in range(n):
        for b in range(n):
            cx = X / 2 - (a + 0.5) * p.cell_pitch
            cy = -Y / 2 + (b + 0.5) * p.cell_pitch
            for part, (Vp, Fp) in cell.items():
                Vp = np.array(Vp, float) + [cx, cy, plate_z(p, cx, cy) + 0.002]
                m.add(f"cells_{part}", Vp, Fp)
    return m


def export_all(p: DesignParams, outdir):
    import os
    os.makedirs(outdir, exist_ok=True)
    b = building(p)
    with open(os.path.join(outdir, "zenith_plate.mtl"), "w") as f:
        for name, kd in (("plate", "0.85 0.88 0.92"), ("structure", "0.35 0.33 0.30"), ("enclosure", "0.75 0.77 0.80"),
                         ("tank", "0.20 0.45 0.80"), ("cells", "0.92 0.93 0.95")):
            f.write(f"newmtl {name}\nKd {kd}\n\n")
    b.write_obj(os.path.join(outdir, "zenith_plate.obj"), "zenith_plate.mtl")
    b.write_stl(os.path.join(outdir, "zenith_plate.stl"))
    c = Mesh()
    for part, (V, F) in funnel_cell_mesh(p).items():
        c.add(part, V, F)
    c.write_stl(os.path.join(outdir, "skin_cell.stl"))
    c.write_obj(os.path.join(outdir, "skin_cell.obj"))
    with open(os.path.join(outdir, "params.json"), "w") as f:
        json.dump({"driving": asdict(p), "derived": p.derived()}, f, indent=1, default=float)
    return b
